using ToolCallsInspector.Core.Analysis;

namespace ToolCallsInspector.Web.Services;

public static class CallSlices
{
    /// <summary>Breakdown of a single LLM call: its input composition plus the output it generated.</summary>
    public static IReadOnlyList<BreakdownSlice> For(SpanNode call, bool includeOutput = true)
    {
        var s = call.Span;
        var input = (double)(s.InputTokens ?? 0);
        var output = includeOutput ? (double)(s.OutputTokens ?? 0) : 0;
        var total = input + output;
        var slices = new List<BreakdownSlice>();
        if (includeOutput)
        {
            slices.Add(new(TokenTotals.OutputKey, "LLM output", "Tokens generated by this call (including reasoning).", output, Pct(output, total)));
        }

        var comp = call.Composition;
        var attributed = comp?.Total ?? 0;
        foreach (var category in Enum.GetValues<TokenCategory>())
        {
            var value = comp?.Get(category) ?? 0;
            if (category == TokenCategory.Overhead)
            {
                value += Math.Max(0, input - attributed);
            }

            slices.Add(new(category.ToString(), TokenCategoryInfo.Label(category), TokenCategoryInfo.Description(category), value, Pct(value, total)));
        }

        return slices;
    }

    public static string MethodLabel(AttributionMethod method) => method switch
    {
        AttributionMethod.Content => "measured from content",
        AttributionMethod.Delta => "estimated from token growth",
        _ => "not attributed",
    };

    public static string MethodDescription(AttributionMethod method) => method switch
    {
        AttributionMethod.Content => "The prompt content was captured, tokenized locally (o200k) and scaled to the token count reported by the model.",
        AttributionMethod.Delta => "No usable prompt content: categories are inferred from how much the reported input grew since the previous call and which tools ran in between.",
        _ => "This call reported no input tokens.",
    };

    private static double Pct(double value, double total) => total > 0 ? value / total * 100 : 0;
}
